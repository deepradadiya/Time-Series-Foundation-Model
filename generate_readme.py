def _generate_pretraining_details() -> str:
    """Generate the Pretraining Details section.

    Includes domain names, total training steps, and loss curves image reference.

    Returns:
        A markdown string with pretraining details.
    """
    from config import Config

    # Compute approximate total training steps
    # Assuming ~1000 samples per domain, 3 domains, batch_size=32, accumulation=4
    # effective_batch = 32 * 4 = 128
    # steps_per_epoch ≈ (3000 / 128) ≈ 24
    # total_steps = 20 epochs * 24 steps ≈ 480
    steps_per_epoch = 24  # approximate
    total_steps = Config.PRETRAIN_EPOCHS * steps_per_epoch

    section = f"""## Pretraining Details

The model is pretrained using Masked Patch Modeling across three diverse domains:

| Domain | Description |
|--------|-------------|
| Energy | Electricity transformer temperature and power consumption data |
| Weather | Meteorological measurements including temperature and humidity |
| Finance | Financial market time series with price and volume data |

**Training Configuration:**
- Total training steps: ~{total_steps} (over {Config.PRETRAIN_EPOCHS} epochs)
- Mask ratio: {Config.MASK_RATIO:.0%} of patches
- Optimizer: AdamW (lr={Config.PRETRAIN_LR}, weight_decay={Config.WEIGHT_DECAY})
- Batch size: {Config.PRETRAIN_BATCH_SIZE} × {Config.GRADIENT_ACCUMULATION} gradient accumulation = {Config.PRETRAIN_BATCH_SIZE * Config.GRADIENT_ACCUMULATION} effective
- Warmup: {Config.WARMUP_EPOCHS} epochs with cosine decay to {Config.MIN_LR}

![Pretraining Loss Curves](assets/pretraining_loss_curves.png)"""

    return section


