def generate_readme(
    metrics_path: str = "evaluation/results/final_metrics.json",
) -> str:
    """Generate the final README.md content.

    Assembles all sections in order: What This Is, Architecture Diagram,
    Results Table, Pretraining Details, How to Reproduce, Resume Bullet,
    and Links. Reads metrics from the specified JSON file (uses placeholder
    values if the file doesn't exist) and config from config.py.

    Args:
        metrics_path: Path to the final_metrics.json file.
            Defaults to "evaluation/results/final_metrics.json".

    Returns:
        The complete README content as a string. Also writes to README.md.
    """
    # Load metrics in both formats needed by different section generators
    table_metrics = _load_metrics(metrics_path)
    resume_metrics = _build_metrics_for_resume(metrics_path)

    # Assemble all sections
    sections = []

    # Title
    sections.append("# Time Series Foundation Model\n")

    # What This Is
    sections.append("## What This Is\n")
    sections.append(generate_what_this_is())
    sections.append("")

    # Architecture Diagram
    sections.append("## Architecture\n")
    sections.append(_generate_architecture_diagram())
    sections.append("")

    # Results Table
    sections.append("## Results\n")
    sections.append(
        "Benchmark results on ETTh1 (Electricity Transformer Temperature hourly) dataset:\n"
    )
    sections.append(generate_results_table(table_metrics))
    sections.append("")

    # Pretraining Details
    sections.append(_generate_pretraining_details())
    sections.append("")

    # How to Reproduce
    sections.append("## How to Reproduce\n")
    sections.append(generate_how_to_reproduce())
    sections.append("")

    # Resume Bullet
    sections.append("## Key Achievement\n")
    sections.append(generate_resume_bullet(resume_metrics))
    sections.append("")

    # Links
    sections.append(_generate_links_section())
    sections.append("")

    content = "\n".join(sections)

    # Write output to README.md
    with open("README.md", "w") as f:
        f.write(content)

    return content


if __name__ == "__main__":
    readme_content = generate_readme()
    print(f"README.md generated successfully ({len(readme_content)} characters)")
